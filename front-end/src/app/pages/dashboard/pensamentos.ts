/** Seleciona uma frase por data civil de Brasília, sem aleatoriedade ou armazenamento. */
export function pensamentoDoDia(agora=new Date()):string {
 const partes=new Intl.DateTimeFormat('pt-BR',{timeZone:'America/Sao_Paulo',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(agora);
 const parte=(tipo:string)=>Number(partes.find(p=>p.type===tipo)?.value);
 const dia=Date.UTC(parte('year'),parte('month')-1,parte('day'));
 const indice=Math.floor((dia-Date.UTC(2026,0,1))/86400000);
 return PENSAMENTOS[((indice%PENSAMENTOS.length)+PENSAMENTOS.length)%PENSAMENTOS.length];
}
